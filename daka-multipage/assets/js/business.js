function bindCardActs(m, box){
  box.querySelectorAll('[data-act]').forEach(b=>{
    b.addEventListener('click', e=>{
      e.stopPropagation();
      const id = b.closest('[data-id]').dataset.id;
      const act = b.dataset.act;
      const r = m.records.find(x=>x.id===id);
      if(!r) return;
      if(act==='view') openDrawer(m, r);
      else if(act==='edit') openPublish(m, r);
      else if(act==='toggle') actToggle(m, r);
      else if(act==='del') actDel(m, r);
      else if(act==='submit') actSubmit(m, r);
      else if(act==='publish') actPublishProj(m, r);
      else if(act==='publishContent') actPublishContent(m, r);
      else if(act==='withdraw') actWithdraw(m, r);
      else if(act==='apply') actApply(m, r);
    });
  });
}

