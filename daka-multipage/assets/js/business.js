function actApply(m,r){
  const isCo = state.acting === 'company';
  if(isApplied(m,r)){
    toast('你'+m.personDone+'该'+m.noun);
    return;
  }
  appliedSet(m).add(r.id);
  /* 从 AI 职业规划等非列表页打开抽屉时，页面内没有列表容器，跳过重渲染 */
  if($('mCards')) renderList(m);
  /* 企业端没有「我的申请」，改用顾问回访口径 */
  toast(isCo ? '报名成功，课程顾问将在 1 个工作日内与你联系' : m.personToast, 'ok');
}

