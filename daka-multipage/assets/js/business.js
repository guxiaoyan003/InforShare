/* 金额区：返回 {main, sub}，sub 用于「13薪」「原价」这类后缀 */
function cardAmount(m, r){
  if(m.schema === 'project'){
    return { main: r.budget || '面议', sub:'', unit:'预算' };
  }
  /* 课程：价格写作「¥3600（原价 ¥4200）」，拆成主价 + 原价后缀 */
  if((m.baseKey||m.key) === 'train'){
    const p = (r.tfacts||[]).find(x=>x[0]==='价格');
    if(p){
      const mm = String(p[1]).match(/^(.*?)（原价\s*(.*?)）$/);
      if(mm) return { main:mm[1], sub:'原价 '+mm[2], unit:'学费', flat:true };
      return { main:String(p[1]), sub:'', unit:'学费' };
    }
    return { main:payName(r.pay), sub:'', unit:'学费' };
  }
  /* 岗位类优先取薪资字段（形如 15-20K·13薪） */
  if(r.salary){
    const parts = String(r.salary).split('·');
    return { main: parts[0], sub: parts[1] || '', unit:'薪资' };
  }
  /* 服务类从 tfacts 里取价格 / 费用 / 报酬 / 补贴 / 套餐 */
  const tf = r.tfacts || [];
  const priceKey = ['价格','费用','报酬','补贴','套餐','课时费'].find(k=>tf.some(p=>p[0]===k));
  if(priceKey){
    const v = tf.find(p=>p[0]===priceKey)[1];
    return { main: v, sub:'', unit: priceKey };
  }
  return { main: payName(r.pay), sub:'', unit: m.payLabel };
}

/* 元信息行：地址 | 年限 | 学历（课程为 地址 | 周期 | 开课） */
function cardMeta(m, r){
  if(m.schema === 'project'){
    return [ r.catg, r.coop, r.cycle ? ('周期 ' + r.cycle) : '', '截止 ' + (r.deadline||'—') ].filter(Boolean);
  }
  const area = r.online ? '线上' : (r.city ? r.city+'·'+r.dist : '—');
  /* 课程：地址 | 课程周期 | 开课日期（形如 深圳·南山区 | 6周 | 2026.11.10开课） */
  if((m.baseKey||m.key) === 'train'){
    /* 纯线上课程不再重复写「线上」（右侧标签已标明） */
    const out = [];
    if(!r.online) out.push(area);
    if(r.cycle) out.push(String(r.cycle).replace(/\s+/g,''));
    const kai = (r.tfacts||[]).find(x=>x[0]==='开课');
    if(kai) out.push(String(kai[1]).replace(/-/g,'.')+'开课');
    return out;
  }
  const out = [area];
  if(r.exp) out.push(r.exp);
  if(r.edu) out.push(r.edu);
  if((m.baseKey||m.key)==='outs' && r.cycle) out.push('周期 '+r.cycle);
  return out;
}

